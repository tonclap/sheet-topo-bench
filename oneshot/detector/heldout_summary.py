"""The held-out exam's table and its summary sentence, from the reports alone.

TOPO-012's deliverable is a dev-vs-held-out table with the worst band published
alongside the best, and PROTOCOL §8 requires the summary sentence of any report
to be generated by the same code as the table — the wave-2 lesson being that a
hand-written summary survives a re-run and silently goes stale. This script is
that code: it reads the four detector reports and two baseline reports, prints
the markdown table, and prints the summary sentence from the same dicts. It
computes nothing new — every number is copied from a report a run produced.

Extension of 19.08.2026 (TOPO-025, held-out v2): when the v2 exam reports are
on disk (``detector_v1_*_h2.json``, ``exam_v5lu_*_h2.json``, see the PROTOCOL
§6 insert of 19.08.2026), the same machinery appends the v2 table — a v1 row
and a v5lu row per corpus — plus the declared reading rule: the paired
bootstrap delta v5lu − v1 on shared resamples (ablation_summary_v5's
construction), with the verdict spelled from the interval. Reports absent →
section absent; nothing of the v1 output changes.

Usage (from oneshot/detector/):

    python heldout_summary.py --topo ../../output/topo --out HELDOUT_RESULTS.md
"""
import argparse
import json
import os

import numpy as np

import sys
# A Windows console defaults to a legacy code page, and the records below carry
# Cyrillic, Delta and the minus sign. Substitute the unrepresentable rather than
# raise: the numbers are the payload, and a UnicodeEncodeError would hide all of
# them behind the first one that does not fit.
for _stream in (sys.stdout, sys.stderr):
    if hasattr(_stream, 'reconfigure'):
        _stream.reconfigure(errors='replace')

BOOTSTRAP_RESAMPLES = 2000
BOOTSTRAP_SEED = 20260815


def bootstrap_ci(report, injection_info=None):
    """95 % percentile CI for AP and recall@N, bootstrapped over injections.

    The 15.08 review named the missing piece: at N = 68 a point estimate has
    no width, and the field's judge publishes metrics with intervals. The
    resampling unit is the injection (the ground-truth item), and nothing is
    re-run: the width comes from the exam's single sanctioned ranking.

    Be precise about *which* bootstrap this is, because two plausible ones
    differ. AP decomposes exactly into one non-negative contribution per
    injection (precision at the rank where it was credited, zero if never
    found), and it is those contributions, computed once from the sanctioned
    ranking, that are resampled — multiplicity acts as weight on a fixed term.
    It is **not** the heavier estimator that re-derives the ranking inside
    each resample, where dropping an injection would demote the windows
    credited to it to false positives and change the precision seen by every
    later injection. The lighter one is what the intervals below report; on
    the original sample the two agree by construction, and the choice is
    recorded here so the intervals are not read as more than they are.

    TARGET item 5 (15.08) extends the same resamples to every number of the
    published row: with `injection_info` ({id: (type, plausible, band)},
    read from the corpus manifest) the subgroup recalls (S/M/H, locally
    plausible, worst band) get intervals from the identical bootstrap —
    a resample's subgroup recall is the mean over its members present in
    that resample; resamples with an empty subgroup are skipped for it.
    """
    outcomes = report.get('per_rank_outcomes')
    ranks = report.get('per_injection_rank')
    if not outcomes or not ranks:
        return None
    ids = sorted(ranks)
    n = len(ids)
    # AP decomposes into one non-negative contribution per injection:
    # AP = (1/n) * sum over found injections of precision at their credited
    # rank. The contributions are computed once from the sanctioned ranking;
    # the bootstrap resamples them (with the zeros of the never-found
    # injections) and takes percentile bounds of the resampled means.
    contribution = {injection: 0.0 for injection in ids}
    tp = 0
    for i, credited in enumerate(outcomes, 1):
        if credited is not None:
            tp += 1
            contribution[credited] = tp / i
    ap_terms = np.array([contribution[injection] for injection in ids])
    recall_terms = np.array([1.0 if ranks[injection] is not None
                             and ranks[injection] <= n else 0.0
                             for injection in ids])
    rng = np.random.default_rng(BOOTSTRAP_SEED)
    samples = rng.integers(0, n, size=(BOOTSTRAP_RESAMPLES, n))
    aps = ap_terms[samples].mean(axis=1)
    recalls = recall_terms[samples].mean(axis=1)
    out = {'ap': (float(np.percentile(aps, 2.5)),
                  float(np.percentile(aps, 97.5))),
           'recall': (float(np.percentile(recalls, 2.5)),
                      float(np.percentile(recalls, 97.5)))}
    if injection_info:
        subgroups = {}
        types = sorted({injection_info[i][0] for i in ids
                        if i in injection_info})
        for t in types:
            subgroups[t] = np.array(
                [1.0 if i in injection_info and injection_info[i][0] == t
                 else 0.0 for i in ids])
        subgroups['plausible'] = np.array(
            [1.0 if i in injection_info and injection_info[i][1] else 0.0
             for i in ids])
        bands = report.get('recall_by_band') or {}
        if bands:
            worst = min(bands, key=bands.get)
            subgroups['worst_band'] = np.array(
                [1.0 if i in injection_info and injection_info[i][2] == worst
                 else 0.0 for i in ids])
        out['subgroups'] = {}
        for label, member in subgroups.items():
            if not member.any():
                continue
            hits = (recall_terms * member)[samples].sum(axis=1)
            sizes = member[samples].sum(axis=1)
            ok = sizes > 0
            values = hits[ok] / sizes[ok]
            out['subgroups'][label] = (float(np.percentile(values, 2.5)),
                                       float(np.percentile(values, 97.5)))
    return out


def load_injection_info(report):
    """{id: (type, plausible, band-label)} from the corpus manifest the report
    itself names; None if the manifest is not on disk (the summary then keeps
    point estimates, it does not guess)."""
    path = os.path.join(report.get('corpus', ''), 'manifest.json')
    if not os.path.exists(path):
        return None
    with open(path, encoding='utf-8') as f:
        manifest = json.load(f)
    return {r['id']: (r['type'], bool(r.get('plausible')),
                      f"w{r['band'] * 10:03d}-{r['band'] * 10 + 9:03d}")
            for r in manifest['injections']}


def load(topo, name):
    path = os.path.join(topo, name)
    if not os.path.exists(path):
        return None
    with open(path, encoding='utf-8') as f:
        return json.load(f)


def fmt(value, digits=4):
    if value is None:
        return 'n/a'
    return f'{value:.{digits}f}'


def detector_row(label, report, erl_jack=None):
    m = report['metrics']
    t = report['recall_by_type']
    ci = bootstrap_ci(report, load_injection_info(report))
    subgroups = (ci or {}).get('subgroups', {})
    ap = fmt(m['ap'])
    recall = fmt(m['recall_at_n'], 3)
    if ci is not None:
        ap += f" [{ci['ap'][0]:.3f}–{ci['ap'][1]:.3f}]"
        recall += f" [{ci['recall'][0]:.3f}–{ci['recall'][1]:.3f}]"

    def with_ci(value, key, digits=3):
        cell = fmt(value, digits)
        if value is not None and key in subgroups:
            lo, hi = subgroups[key]
            cell += f" [{lo:.2f}–{hi:.2f}]"
        return cell

    erl = f"{m['delta_erl_mm']:+.2f}"
    if erl_jack:
        lo, hi = erl_jack['delta_erl_mm']['ci95']
        erl += f" [{lo:+.2f}–{hi:+.2f}]"
    context = report.get('erl_context')
    if context:
        oracle = context['delta_erl_oracle_mm']
        if oracle > 0:
            erl += f" ({m['delta_erl_mm'] / oracle:.0%} of oracle)"
    return (f"| {label} | {report['scoped_injections']} | {ap} | "
            f"{recall} | {with_ci(t.get('S'), 'S')} | "
            f"{with_ci(t.get('M'), 'M')} | {with_ci(t.get('H'), 'H')} | "
            f"{with_ci(report.get('recall_on_locally_plausible'), 'plausible')} | "
            f"{erl} |")


def baseline_rows(label, report):
    rows = []
    for ch, title in (('selfx', 'self-intersections'),
                      ('rayinv', 'ray inversions')):
        raw = report[f'{ch}_raw']['metrics']['ap']
        atlas = report[f'{ch}_atlas']['metrics']['ap']
        rows.append(f"| {label}: {title} | {fmt(raw)} | {fmt(atlas)} |")
    return rows


def band_lines(report):
    bands = report.get('recall_by_band') or {}
    if not bands:
        return [], None, None
    worst = min(bands, key=bands.get)
    best = max(bands, key=bands.get)
    lines = [f"| {b} | {fmt(v, 3)} |" for b, v in bands.items()]
    return lines, (worst, bands[worst]), (best, bands[best])


def paired_delta_lines(report, injection_info):
    """The declared reading rule of the v2 exam (PROTOCOL §6 insert,
    19.08.2026): paired per-resample deltas v5lu − v1 from one exam report
    (top-level block vs ablation_v1_config), shared resamples, verdict from
    the ΔAP interval. Construction is ablation_summary_v5's, unchanged."""
    from ablation_summary import config_terms
    v1_block = report['ablation_v1_config']
    v5_block = {key: report[key] for key in
                ('metrics', 'recall_by_type', 'recall_by_band',
                 'recall_on_locally_plausible', 'per_rank_outcomes',
                 'per_injection_rank')}
    ids = sorted(report['per_injection_rank'])
    n = len(ids)
    rng = np.random.default_rng(BOOTSTRAP_SEED)
    samples = rng.integers(0, n, size=(BOOTSTRAP_RESAMPLES, n))
    info = injection_info or {}
    members = {}
    for label, select in (
            ('S', lambda i: info.get(i, (None,))[0] == 'S'),
            ('M', lambda i: info.get(i, (None,))[0] == 'M'),
            ('H', lambda i: info.get(i, (None,))[0] == 'H'),
            ('plausible', lambda i: bool(info.get(i, (None, False))[1]))):
        members[label] = np.array([1.0 if select(i) else 0.0 for i in ids])

    resampled = {}
    for tag, block in (('v1', v1_block), ('v5lu', v5_block)):
        ap_terms, recall_terms = config_terms(block, ids)
        entry = {'ap': ap_terms[samples].mean(axis=1),
                 'recall': recall_terms[samples].mean(axis=1)}
        for sub, member in members.items():
            if not member.any():
                continue
            hits = (recall_terms * member)[samples].sum(axis=1)
            sizes = member[samples].sum(axis=1)
            ok = sizes > 0
            entry[sub] = hits[ok] / sizes[ok]
        resampled[tag] = entry

    cells = []
    verdict = None
    for key in ('ap', 'recall', 'S', 'M', 'H', 'plausible'):
        if key not in resampled['v1'] or key not in resampled['v5lu']:
            cells.append('n/a')
            continue
        a, b = resampled['v5lu'][key], resampled['v1'][key]
        # Both tags drop the same resamples (the empty-subgroup mask is a
        # function of `member` and `samples`, which they share), so the arrays
        # are aligned element-for-element. Assert rather than truncate: a
        # length mismatch would mean the masks diverged, and pairing resample
        # i of one with resample j of the other would silently produce a wrong
        # interval instead of a failure.
        assert len(a) == len(b), (
            f'paired delta {key}: {len(a)} vs {len(b)} resamples — the '
            f'empty-subgroup masks diverged, deltas would be misaligned')
        delta = a - b
        lo = float(np.percentile(delta, 2.5))
        hi = float(np.percentile(delta, 97.5))
        point = float(np.mean(delta))
        mark = ' **significant**' if lo > 0 or hi < 0 else ''
        cells.append(f'{point:+.3f} [{lo:+.2f}–{hi:+.2f}]{mark}')
        if key == 'ap':
            if lo > 0:
                verdict = ('outcome (a): paired ΔAP significant > 0 — '
                           'the dev gain TRANSFERS')
            elif hi < 0:
                verdict = ('outcome (c): paired ΔAP significant < 0 — '
                           'the dev gain FAILS to transfer')
            else:
                verdict = ('outcome (b): paired ΔAP not significant — '
                           'transfer of the dev gain not demonstrated')
    return cells, verdict


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--topo', default=os.path.join('..', '..', 'output',
                                                       'topo'))
    parser.add_argument('--out', default=None,
                        help='markdown file to write; stdout always gets a copy')
    args = parser.parse_args()

    reports = {
        'dev': load(args.topo, 'detector_v1_paris4.json'),
        'paris4_heldout': load(args.topo, 'detector_v1_paris4_heldout.json'),
        'pherc0139': load(args.topo, 'detector_v1_0139.json'),
    }
    baselines = {
        'dev': load(args.topo, 'baselines_paris4.json'),
        'paris4_heldout': load(args.topo, 'baselines_paris4_heldout.json'),
        'pherc0139': load(args.topo, 'baselines_0139.json'),
    }
    labels = {
        'dev': 'Dev (Paris 4, bands < 100)',
        'paris4_heldout': 'Held-out A (Paris 4, bands ≥ 100)',
        'pherc0139': 'Held-out B (PHerc0139, whole scroll)',
    }

    lines = ['# Held-out exam — summary (generated by heldout_summary.py)',
             '',
             '_AP and recall@N carry 95 % bootstrap intervals over injections '
             f'({BOOTSTRAP_RESAMPLES} resamples, seed {BOOTSTRAP_SEED}); the '
             'S/M/H, locally-plausible and worst-band intervals come from the '
             'same resamples; a difference between rows whose intervals '
             'overlap is sampling noise, not an effect. ΔERL@N is over the '
             'whole corpus at once; its interval is a per-segment jackknife '
             '(`jackknife_erl.py`, ±1.96 SE), normalised as a share of the '
             'oracle ΔERL (cuts at the true positions, the §3 ceiling)._',
             '',
             '| corpus | N | AP [95 % CI] | recall@N [95 % CI] | S | M | H | '
             'plausible | ΔERL@N mm |',
             '|---|---|---|---|---|---|---|---|---|']
    erl_jack = load(args.topo, 'erl_jackknife.json') or {}
    for key in ('dev', 'paris4_heldout', 'pherc0139'):
        if reports[key] is not None:
            lines.append(detector_row(labels[key], reports[key],
                                      erl_jack.get(key)))

    erl_rows = []
    for key in ('dev', 'paris4_heldout', 'pherc0139'):
        report = reports[key]
        if report is None or not report.get('erl_context'):
            continue
        context = report['erl_context']
        m = report['metrics']
        erl_rows.append(
            f"| {labels[key]} | {m['erl_broken_mm']:.1f} | "
            f"{m['delta_erl_mm']:+.3f} | "
            f"{context['delta_erl_oracle_mm']:+.3f} | "
            f"{context['delta_erl_random_mm_median10']:+.3f} |")
    if erl_rows:
        lines += ['', '## ΔERL@N against the ceiling and the floor (§3)', '',
                  '| corpus | ERL of the corrupted grid, mm | detector | '
                  'oracle (ceiling) | random windows (median of 10 seeds) |',
                  '|---|---|---|---|---|'] + erl_rows

    lines += ['', '## §7 baselines (AP: raw / with atlas differencing)', '',
              '| baseline | AP raw | AP atlas |', '|---|---|---|']
    for key in ('dev', 'paris4_heldout', 'pherc0139'):
        if baselines[key] is not None:
            lines += baseline_rows(labels[key], baselines[key])

    # ---- Held-out v2 (TOPO-025, PROTOCOL §6 insert of 19.08.2026) ----
    v2_reports = {
        'paris4_h2_v1': load(args.topo, 'detector_v1_paris4_h2.json'),
        'paris4_h2_v5lu': load(args.topo, 'exam_v5lu_paris4_h2.json'),
        '0139_h2_v1': load(args.topo, 'detector_v1_0139_h2.json'),
        '0139_h2_v5lu': load(args.topo, 'exam_v5lu_0139_h2.json'),
    }
    v2_baselines = {
        'paris4_h2': load(args.topo, 'baselines_paris4_h2.json'),
        '0139_h2': load(args.topo, 'baselines_0139_h2.json'),
    }
    v2_labels = {
        'paris4_h2_v1': 'Held-out A2 (Paris 4 ≥ 100, seed 20260819): v1',
        'paris4_h2_v5lu': 'Held-out A2 (Paris 4 ≥ 100, seed 20260819): v5lu',
        '0139_h2_v1': 'Held-out B2 (PHerc0139, seed 20260819): v1',
        '0139_h2_v5lu': 'Held-out B2 (PHerc0139, seed 20260819): v5lu',
    }
    v2_summary = []
    if any(v2_reports[k] is not None for k in v2_reports):
        erl_jack_h2 = load(args.topo, 'erl_jackknife_h2.json') or {}
        lines += ['', '## Held-out v2 — the v5lu exam (TOPO-025, PROTOCOL '
                      '§6 insert of 19.08.2026)', '',
                  '_The exam question: does the dev gain v5lu − v1 '
                  '(+0.211 AP) transfer? The v1 rows come from detect_v1 on '
                  'the new corpus; the v5lu rows from exam_v5lu (trained on '
                  'the full dev pool, applied frozen). The reading rule was '
                  'declared before the run: the verdict is read off the '
                  'paired ΔAP interval._', '',
                  '| corpus | N | AP [95 % CI] | recall@N [95 % CI] | S | '
                  'M | H | plausible | ΔERL@N mm |',
                  '|---|---|---|---|---|---|---|---|---|']
        for key in ('paris4_h2_v1', 'paris4_h2_v5lu',
                    '0139_h2_v1', '0139_h2_v5lu'):
            if v2_reports[key] is not None:
                lines.append(detector_row(v2_labels[key], v2_reports[key],
                                          erl_jack_h2.get(key)))
        delta_header_done = False
        for corpus_key, exam_key in (('A2 (Paris 4 ≥ 100)', 'paris4_h2_v5lu'),
                                     ('B2 (PHerc0139)', '0139_h2_v5lu')):
            report = v2_reports[exam_key]
            if report is None or 'ablation_v1_config' not in report:
                continue
            if not delta_header_done:
                lines += ['', '### Paired delta v5lu − v1 '
                              '(same resamples, the declared reading rule)',
                          '',
                          '| corpus | ΔAP | Δrecall@N | ΔS | ΔM | ΔH | '
                          'Δplausible |', '|---|---|---|---|---|---|---|']
                delta_header_done = True
            cells, verdict = paired_delta_lines(
                report, load_injection_info(report))
            lines.append(f'| {corpus_key} | ' + ' | '.join(cells) + ' |')
            v2_summary.append(f'{corpus_key}: {verdict}')
        if v2_summary:
            lines += [''] + [f'**{s}.**' for s in v2_summary]
        if any(v2_baselines[k] is not None for k in v2_baselines):
            lines += ['', '### §7 baselines on the v2 corpora '
                          '(AP: raw / with atlas differencing)', '',
                      '| baseline | AP raw | AP atlas |', '|---|---|---|']
            for key, label in (('paris4_h2', 'A2 (Paris 4 ≥ 100)'),
                               ('0139_h2', 'B2 (PHerc0139)')):
                if v2_baselines[key] is not None:
                    lines += baseline_rows(label, v2_baselines[key])
        for key in ('paris4_h2_v5lu', '0139_h2_v5lu'):
            report = v2_reports[key]
            if report is None:
                continue
            bands, worst, best = band_lines(report)
            if bands:
                lines += ['', f'### recall@N by winding band — '
                              f'{v2_labels[key]}', '',
                          '| band | recall@N |', '|---|---|'] + bands
                ci = bootstrap_ci(report, load_injection_info(report)) or {}
                worst_ci = ci.get('subgroups', {}).get('worst_band')
                worst_cell = (f'{worst[1]:.3f}'
                              + (f' [{worst_ci[0]:.2f}–{worst_ci[1]:.2f}]'
                                 if worst_ci else ''))
                lines.append(f'\nWorst band **{worst[0]} = {worst_cell}**, '
                             f'best {best[0]} = {best[1]:.3f} '
                             f'(PROTOCOL §8).')

    summary = []
    for key in ('paris4_heldout', 'pherc0139'):
        report = reports[key]
        if report is None:
            continue
        bands, worst, best = band_lines(report)
        if bands:
            lines += ['', f'## recall@N by winding band — {labels[key]}', '',
                      '| band | recall@N |', '|---|---|'] + bands
            ci = bootstrap_ci(report, load_injection_info(report)) or {}
            worst_ci = ci.get('subgroups', {}).get('worst_band')
            worst_cell = (f'{worst[1]:.3f}'
                          + (f' [{worst_ci[0]:.2f}–{worst_ci[1]:.2f}]'
                             if worst_ci else ''))
            lines.append(f'\nWorst band **{worst[0]} = {worst_cell}**, '
                         f'best {best[0]} = {best[1]:.3f} (PROTOCOL §8).')
        m = report['metrics']
        summary.append(f"{labels[key]}: AP {m['ap']:.4f}, "
                       f"recall@N {m['recall_at_n']:.3f}"
                       + (f", worst band {worst[0]} = {worst[1]:.3f}"
                          if worst else ''))
    if reports['dev'] is not None:
        summary.insert(0, f"dev reference point AP "
                          f"{reports['dev']['metrics']['ap']:.4f}")
    sentence = 'In one line: ' + '; '.join(summary) + '.'
    if v2_summary:
        sentence += (' Held-out v2 (the v5lu exam): '
                     + '; '.join(v2_summary) + '.')
    lines += ['', sentence, '']

    text = '\n'.join(lines)
    print(text)
    if args.out:
        with open(args.out, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
        print(f'written to {args.out}')


if __name__ == '__main__':
    main()
